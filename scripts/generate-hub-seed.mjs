#!/usr/bin/env node
// Generate a Supabase seed migration that publishes this pack's skills into a
// `skill_templates` table (the 6DuckLearn hosted skills system).
//
//   node scripts/generate-hub-seed.mjs > <migration>.sql
//
// Regenerate on every release rather than hand-editing the SQL: the pack is the
// source of truth, and drift between the repo and the hosted catalog is the
// failure this script exists to prevent.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const stack = JSON.parse(fs.readFileSync(path.join(root, 'stack.json'), 'utf8'));

// Hosted-schema limits (supabase/migrations/20260111000000_create_skill_templates.sql)
const NAME_MAX = 64;
const DESC_MAX = 1024;
const NAME_RE = /^[a-z0-9-]+$/;

const CATEGORY = 'strategy';

// Loop stage → tags, so the hosted catalog can present the campaign order.
const STAGE = {
  'sunzi-strategy-consultant': 'orchestrator',
  'sunzi-alignment': 'audit', 'sunzi-timing': 'audit', 'sunzi-terrain': 'audit',
  'sunzi-command': 'audit', 'sunzi-method': 'audit',
  'sunzi-compare': 'count',
  'sunzi-win-without-fighting': 'devise', 'sunzi-find-the-wedge': 'devise',
  'sunzi-contingency': 'devise', 'sunzi-intelligence': 'devise',
  'sunzi-stakeholder-ssr': 'test', 'strategy-analyst-review': 'test',
  'sunzi-restraint': 'decide',
  'sunzi-retro': 'reflect',
  'sunzi-decision-review': 'standalone',
  'sunzi-focus-group-skill-review': 'standalone',
};

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs) => `ARRAY[${xs.map(q).join(', ')}]::TEXT[]`;

function parseFrontmatter(content, rel) {
  const m = content.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error(`${rel}: missing frontmatter`);
  const fm = {};
  let key = null;
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-z-]+):\s*(.*)$/);
    if (kv) { key = kv[1]; fm[key] = kv[2] ? kv[2].trim() : []; continue; }
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && key) { if (!Array.isArray(fm[key])) fm[key] = []; fm[key].push(item[1].trim()); }
  }
  return { fm, body: content.slice(m[0].length) };
}

// Referenced local files travel with the skill in `resources`, because the
// hosted runtime has no ../../references/ path to resolve.
function collectResources(body) {
  const out = {};
  for (const m of body.matchAll(/\]\((\.\.\/\.\.\/references\/[^)]+)\)/g)) {
    const rel = m[1].replace(/^\.\.\/\.\.\//, '');
    const abs = path.join(root, rel);
    if (fs.existsSync(abs) && !out[rel]) out[rel] = fs.readFileSync(abs, 'utf8');
  }
  return out;
}

const rows = [];
const problems = [];

for (const skill of stack.skills) {
  const rel = skill.path;
  const raw = fs.readFileSync(path.join(root, rel), 'utf8');
  const { fm, body } = parseFrontmatter(raw, rel);

  const name = fm.name;
  const description = fm.description ?? '';
  if (!NAME_RE.test(name) || name.length > NAME_MAX) problems.push(`${name}: name violates hosted constraint`);
  if (description.length > DESC_MAX) problems.push(`${name}: description ${description.length} > ${DESC_MAX} chars`);
  if (/anthropic|claude/i.test(name)) problems.push(`${name}: name contains a reserved vendor token`);

  const stage = STAGE[name] ?? 'standalone';
  const tags = ['sunzi', 'strategy', `stage:${stage}`, ...(fm.triggers ?? []).slice(0, 3).map((t) => t.toLowerCase())];

  const resources = collectResources(body);
  rows.push({ name, description, tags, content: raw, version: fm.version ?? stack.version, resources });
}

if (problems.length) {
  console.error('generate-hub-seed: hosted-schema violations\n  ' + problems.join('\n  '));
  process.exit(1);
}

const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, '');
const out = [];
out.push(`-- Seed 6DuckLearn Sunzi Strategy Stack v${stack.version} into skill_templates`);
out.push(`-- GENERATED by scripts/generate-hub-seed.mjs in ${stack.public_repo}`);
out.push('-- Do not hand-edit: regenerate from the pack on each release.');
out.push(`-- Source of truth: ${stack.public_repo} @ v${stack.version}`);
out.push(`-- Generated: ${stamp}  ·  ${rows.length} skills`);
out.push('');
out.push('BEGIN;');
out.push('');
out.push('-- Idempotent: re-running replaces the pack rows and leaves user skills untouched.');
out.push(`DELETE FROM skill_templates WHERE user_id IS NULL AND 'sunzi' = ANY(tags);`);
out.push('');
out.push('INSERT INTO skill_templates (name, description, category, tags, content, version, is_public, user_id, resources) VALUES');

const values = rows.map((r) => [
  '(', q(r.name), ',\n ', q(r.description), ',\n ', q(CATEGORY), ',\n ', arr(r.tags),
  ',\n ', q(r.content), ',\n ', q(r.version), ',\n TRUE,\n NULL,\n ',
  q(JSON.stringify(r.resources)), '::jsonb)',
].join(''));

out.push(values.join(',\n\n'));
out.push(';');
out.push('');
out.push('COMMIT;');

process.stdout.write(out.join('\n') + '\n');
console.error(`generate-hub-seed: ${rows.length} skills, ${rows.reduce((n, r) => n + Object.keys(r.resources).length, 0)} bundled resources`);
